import fs from 'node:fs';
const m = await (await fetch('https://registry.npmjs.org/dsh-image-gen/latest')).json();
console.log('name/version :', m.name + '@' + m.version);
console.log('description  :', m.description);
console.log('license      :', m.license, '| repo:', m.repository?.url);
console.log('engines      :', JSON.stringify(m.engines));
console.log('dsh.bundle   :', JSON.stringify(m.dsh?.bundle));
console.log('dsh.client   :', JSON.stringify(m.dsh?.client));
console.log('dsh.compat   :', JSON.stringify(m.dsh?.compatibility));
console.log('dshWorkshop  :', JSON.stringify(m.dshWorkshop));
console.log('--- dsh-* peers ---');
for (const [n, r] of Object.entries(m.peerDependencies ?? {})) if (n.startsWith('@deepseek-ai/dsh')) console.log(' ', n.padEnd(44), r);
console.log('--- other peers ---');
for (const [n, r] of Object.entries(m.peerDependencies ?? {})) if (!n.startsWith('@deepseek-ai/dsh')) console.log(' ', n.padEnd(44), r);
console.log('--- install scripts ---');
console.log(' ', Object.keys(m.scripts ?? {}).filter((k) => /install|prepare|prepack|post/.test(k)).join(', ') || '(none)');
const t = await fetch(m.dist.tarball);
const b = Buffer.from(await t.arrayBuffer());
fs.writeFileSync('shanliuling-image-gen.tgz', b);
console.log('tarball:', b.length, 'bytes');
